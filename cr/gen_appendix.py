"""Generate appendix tables (Markdown) from cr/results, cr/eda/summary.json and cr/results_v2/summary_v2.json.

python cr/gen_appendix.py  ->  paper_cr/APPENDIX_TABLES.md
"""
import json
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "paper_cr" / "APPENDIX_TABLES.md"
S1 = json.loads((HERE / "eda" / "summary.json").read_text())
S2 = json.loads((HERE / "results_v2" / "summary_v2.json").read_text())
ORDER = ["t5-tiny", "t5-mini", "t5-small", "t5-base", "t5-large", "timemoe-50m", "bolt-base", "chronos-2"]
STEP = ORDER[:6]
LAB = {"t5-tiny": "Chronos-T5 tiny", "t5-mini": "Chronos-T5 mini", "t5-small": "Chronos-T5 small",
       "t5-base": "Chronos-T5 base", "t5-large": "Chronos-T5 large", "timemoe-50m": "Time-MoE 50M",
       "bolt-base": "Chronos-Bolt base", "chronos-2": "Chronos-2"}
LAW = {"beta": "Beta keep", "iid": "Random dropout", "block": "Block outages", "mnar": "Value-dependent"}


def f(x, d=2):
    return "–" if x is None or pd.isna(x) else f"{x:.{d}f}"


def ci(c):
    sig = "\\*" if (c[1] > 0 or c[2] < 0) else ""
    return f"{c[0]:+.2f}{sig} [{c[1]:+.2f}, {c[2]:+.2f}]"


def table(header, rows):
    s = "| " + " | ".join(header) + " |\n|" + "---|" * len(header) + "\n"
    return s + "".join("| " + " | ".join(r) + " |\n" for r in rows)


md = ["# Appendix tables (generated by `cr/gen_appendix.py`; do not edit by hand)\n"]

# ---------------------------------------------------------------- C1 evaluation schemes
d = pd.concat([pd.read_csv(HERE / "results" / f"{m}.csv") for m in STEP], ignore_index=True)
d = d[(d.series != "__pooled__") & (d.target == "m_perp")]
d = d[d.layer == d.n_layers]
md.append("## C1. Elapsed time m⊥ by evaluation scheme (final layer, single draw, median over 102 series)\n")
md.append("Entries are noise / real. Oracle: position-only Monte Carlo reference.\n")
for law in ("beta", "iid", "block"):
    rows = []
    for p in (0.1, 0.3, 0.5, 0.7):
        oracle = S1["references"][f"step|{law}|{p}|m_perp|mc_oracle"]
        for m in STEP:
            x = d[(d.model == m) & (d.law == law) & (d.p == p)]
            cell = []
            for cv in ("within_shuffled", "within_blocked", "cross"):
                y = x[x.cv == cv].groupby("input").r.median()
                cell.append(f"{f(y.get('noise'))} / {f(y.get('real'))}")
            rows.append([f"{p}", LAB[m], *cell, f(oracle)])
    md.append(f"### {LAW[law]}\n")
    md.append(table(["p", "Model", "Shuffled folds", "Contiguous folds", "Held-out series", "Oracle"], rows))

# ---------------------------------------------------------------- C2 position
md.append("\n## C2. Token position r(k) from white noise (single draw, best layer; input-embedding layer in parentheses)\n")
rows = []
for m in ORDER:
    P = S1["P1_counting"][m]
    rows.append([LAB[m]] + [f"{f(P[f'{law}_noise']['best_r'], 3)} ({f(P[f'{law}_noise']['layer0_r'])})" for law in ("beta", "iid", "block")]
                + [f(S2["cells"][f"{m}|mnar|0.5"]["ridge|k"]["noise"], 3)])
md.append(table(["Model", "Beta keep", "Random dropout", "Block outages", "Value-dependent (3 draws)"], rows))

# ---------------------------------------------------------------- C3 planned gap test
md.append("\n## C3. Pre-specified gap test: median real − noise Δr for Δt, random dropout, p = 0.5\n")
rows = []
for m in ORDER:
    a = S1["P3_keeping_time"][m]
    b = S2["cells"][f"{m}|iid|0.5"]["ridge|dt"]
    rows.append([LAB[m], str(a["layer"]), ci([a["median_delta"], *a["ci95"]]), "pass" if a["keeps_time"] else "fail",
                 str(b["layer"]), ci(b["delta"])])
md.append(table(["Model", "Layer (planned)", "Single draw (planned)", "Criterion", "Layer (3 draws)", "Three draws"], rows))

# ---------------------------------------------------------------- C4 / C5 references
for title, key, refkey, diffkey in (
        ("C4. Gap Δt: model minus difference probe (real input)", "dt", "reader", "minus_reader"),
        ("C5. Elapsed time m⊥: model minus running-sum baseline (real input)", "m_perp", "running_sum", "minus_running_sum")):
    md.append(f"\n## {title}, three draws, 71 evaluation series\n")
    md.append("Each entry: model r, reference r, and median paired difference [95% CI]; \\* = CI excludes 0.\n")
    for law in ("iid", "block", "mnar"):
        rows = []
        for p in (0.5, 0.7):
            for m in ORDER:
                c = S2["cells"][f"{m}|{law}|{p}"]
                out = [f"{p}", LAB[m]]
                for probe in ("ridge", "mlp"):
                    x = c[f"{probe}|{key}"]
                    rk, dk = refkey, diffkey
                    if key == "m_perp" and probe == "ridge" and "running_sum_raw" in x:
                        rk, dk = "running_sum_raw", "minus_running_sum_raw"
                    out.append(f"{f(x['real'])} vs {f(x[rk])}: {ci(x[dk])}")
                rows.append(out)
        md.append(f"### {LAW[law]}\n")
        md.append(table(["p", "Model", "Ridge", "MLP"], rows))

# ---------------------------------------------------------------- C6 smoothness
md.append("\n## C6. Spearman ρ between per-series gap gain (real − noise) and series properties (single draw)\n")
rows = [[LAB[m]] + [f(S1["content_clock_spearman"][m][k]) for k in ("lag1_ac", "roughness", "spec_entropy", "T")] for m in ORDER]
md.append(table(["Model", "Lag-1 autocorrelation", "Roughness", "Spectral entropy", "Length"], rows))

# ---------------------------------------------------------------- C7 draws
md.append("\n## C7. Draw-to-draw spread: median elapsed-time r (ridge, real) per draw at the selected layer\n")
rows = []
for m in ORDER:
    rows.append([LAB[m]] + [" / ".join(f(v) for v in S2["cells"][f"{m}|{law}|0.7"]["ridge|m_perp"].get("per_draw_median", []))
                            for law in ("iid", "block", "mnar")])
md.append(table(["Model", "Random dropout, p = 0.7", "Block outages, p = 0.7", "Value-dependent, p = 0.7"], rows))

# ---------------------------------------------------------------- C8 references
md.append("\n## C8. Position-only references for m⊥ (single draw): Monte Carlo oracle / learned spline of position\n")
rows = []
for law in ("beta", "iid", "block"):
    for p in (0.1, 0.3, 0.5, 0.7):
        r = S1["references"]
        rows.append([LAW[law], f"{p}", f"{f(r[f'step|{law}|{p}|m_perp|mc_oracle'])} / {f(r[f'step|{law}|{p}|m_perp|spline_cross'])}",
                     f"{f(r[f'patch|{law}|{p}|m_perp|mc_oracle'])} / {f(r[f'patch|{law}|{p}|m_perp|spline_cross'])}"])
md.append(table(["Pattern", "p", "Step tokens", "Patches (original targets)"], rows))

OUT.write_text("\n".join(md), encoding="utf-8")
print("written", OUT)
